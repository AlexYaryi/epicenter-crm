export type I18nKey = keyof typeof dict.ru;

export function tr(locale: Locale, key: I18nKey, vars?: Record<string, string | number>): string {
  let value: string = dict[locale][key] ?? dict.ru[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(`{${name}}`, String(replacement));
    }
  }
  return value;
}
